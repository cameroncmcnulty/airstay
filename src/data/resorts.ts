export function nightsBetween(a?: string, b?: string) {
  if (!a || !b) return 7;
  const ms = Date.parse(b) - Date.parse(a);
  if (!Number.isFinite(ms) || ms <= 0) return 7;
  return Math.max(1, Math.round(ms / 86400000));
}

export function matchResorts(q: { to?: string; toCity?: string }) {
  const blob = `${q.to || ""} ${q.toCity || ""}`.toLowerCase();
  const code = (q.to || "").toUpperCase();
  return RESORTS.filter((r) => {
    if (code && r.airports.includes(code)) return true;
    if (blob.includes("cancun") || blob.includes("cancún") || blob.includes("mujeres")) return r.region === "cancun" || r.region === "riviera";
    if (blob.includes("playa") || blob.includes("tulum") || blob.includes("riviera") || blob.includes("xcaret") || blob.includes("carmen"))
      return r.region === "riviera" || r.region === "cancun";
    if (blob.includes("vallarta") || blob.includes("nayarit") || blob.includes("pvr")) return r.region === "vallarta";
    if (blob.includes("cabo") || blob.includes("sjd") || blob.includes("lucas")) return r.region === "cabo";
    if (blob.includes("mexico") || blob.includes("mexique")) return true;
    return false;
  });
}
